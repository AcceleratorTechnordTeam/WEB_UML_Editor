/** Trois couleurs représentatives pour l'aperçu du sélecteur. */
export const swatchOf = (t) => t.swatch ?? [t.colors.bg, t.colors.arrow, t.colors.highlight];

/** Fusionne les skinparam du diagramme dans les couleurs du thème. */
export function resolveColors(theme, skin) {
  const c = { ...theme.colors };
  if (!theme.useSkin) return c;
  const map = {
    participantbordercolor: 'border',
    participantbackgroundcolor: 'partBg',
    arrowcolor: 'arrow',
    sequencelifelinebordercolor: 'lifeline',
    sequencegroupbackgroundcolor: 'groupBg',
    sequencegroupbordercolor: 'groupBorder',
    sequencegroupheaderfontcolor: 'groupHeader',
    notebackgroundcolor: 'noteBg',
    notebordercolor: 'noteBorder',
    backgroundcolor: 'bg',
    defaultfontcolor: 'text',
  };
  for (const [k, v] of Object.entries(map)) if (skin[k]) c[v] = skin[k];
  c.actorBorder = skin.actorbordercolor || c.border;
  c.dbBorder = skin.databasebordercolor || c.border;
  return c;
}
